import { describe, expect, test } from "bun:test"
import { readFileSync, statSync } from "node:fs"
import { mkdtemp, rm } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join, resolve } from "node:path"

import { PI_HOST_PACKAGES } from "../../../../scripts/dependency-pins.ts"
import { toPosix } from "../../../runtime/src/domain/paths.ts"
import { PI_ROOT_PLACEHOLDER } from "../../../runtime/src/hooks/pi-context.ts"
import { FAMILIES } from "../../../runtime/src/instructions/families.ts"
import { instructionsDirectory } from "../../../runtime/src/instructions/skills.ts"
import { build } from "../build.ts"
import packageJson from "../package.json" with { type: "json" }
import { DIST_DIRECTORY, REPOSITORY } from "../src/files.ts"
import {
  bundleExtension,
  DESCRIPTION,
  EXTENSION_OUTPUT,
  generate,
  GENERATED_PATHS,
  HOST_MODULES,
  PACKAGE_FILES,
  PI_FAMILY,
} from "../src/generate.ts"

const read = (...path: Array<string>) => readFileSync(join(REPOSITORY, ...path), "utf8")
const readJson = (...path: Array<string>) => JSON.parse(read(...path)) as Record<string, unknown>

/** The paths of every file below a folder of the repository, relative to the repository. */
const filesBelow = async (path: string): Promise<ReadonlyArray<string>> =>
  (await Array.fromAsync(new Bun.Glob("**/*").scan({ cwd: join(REPOSITORY, path), dot: true })))
    .map((file) => toPosix(join(path, file)))
    .toSorted()

const generated = await generate()
const sourceSkills = (await filesBelow(`${instructionsDirectory(PI_FAMILY)}/skills`)).map((path) =>
  path.slice(`${instructionsDirectory(PI_FAMILY)}/skills/`.length),
)

describe("the generated Pi package is in step with its sources", () => {
  test("every committed generated file equals a fresh build, byte for byte", async () => {
    const root = await mkdtemp(join(tmpdir(), "holyagent-pi-"))
    await build(root)
    for (const file of generated) {
      expect({ path: file.path, text: read(file.path) }).toEqual({
        path: file.path,
        text: file.content,
      })
      expect({ path: file.path, text: await Bun.file(join(root, file.path)).text() }).toEqual({
        path: file.path,
        text: file.content,
      })
    }
    await rm(root, { recursive: true, force: true })
  })

  test("the generated paths hold no file the build does not make", async () => {
    const committed = (await Promise.all(GENERATED_PATHS.map(filesBelow))).flat()
    expect(committed).toEqual(generated.map((file) => file.path))
  })

  test("a build removes any other file of the package", async () => {
    const root = await mkdtemp(join(tmpdir(), "holyagent-pi-"))
    const stale = join(root, DIST_DIRECTORY, "skills", "stale", "SKILL.md")
    await Bun.write(stale, "old")
    await build(root)
    expect(await Bun.file(stale).exists()).toBe(false)
    expect(await Bun.file(join(root, DIST_DIRECTORY, "package.json")).exists()).toBe(true)
    await rm(root, { recursive: true, force: true })
  })

  test("the build is deterministic", async () => {
    expect(await generate()).toEqual(generated)
  })

  test("generated files carry the note where their format allows one", () => {
    for (const file of generated) {
      expect({
        path: file.path,
        noted: file.content.includes("Generated by packages/integrations/pi/build.ts from "),
      }).toEqual({ path: file.path, noted: !file.path.endsWith(".json") })
    }
  })

  test("the commit hook stages exactly the generated paths", () => {
    const lefthook = Bun.YAML.parse(read("lefthook.yml")) as {
      readonly "pre-commit": { readonly jobs: ReadonlyArray<{ name: string; run?: string }> }
    }
    const job = lefthook["pre-commit"].jobs.find(({ name }) => name === "build-pi")
    const [, paths = ""] = (job?.run ?? "").split(/\s--\s/)
    expect(job?.run).toStartWith("git add -A -- ")
    expect(paths.split(/\s+/).filter((path) => path !== "")).toEqual([...GENERATED_PATHS])
  })
})

describe("the package manifest", () => {
  const manifest = JSON.parse(
    generated.find((file) => file.path === `${DIST_DIRECTORY}/package.json`)?.content ?? "{}",
  ) as Record<string, unknown>

  test("is a Pi package named and versioned from the workspace package", () => {
    expect(manifest).toMatchObject({
      name: "holyagent",
      version: packageJson.version,
      description: DESCRIPTION,
      keywords: ["pi-package"],
      license: "Apache-2.0",
    })
    expect(packageJson.version).toBe(readJson("package.json")["version"] as string)
  })

  test("lists the extension and skill folders under the pi key, and they exist", () => {
    expect(manifest["pi"]).toEqual({ extensions: ["./extensions"], skills: ["./skills"] })
    const built = generated.map((file) => file.path.slice(`${DIST_DIRECTORY}/`.length))
    expect(built).toContain(EXTENSION_OUTPUT)
    expect(built.some((path) => path.startsWith("skills/"))).toBe(true)
  })

  test("declares the host modules as peers with the range * and bundles none", () => {
    expect(manifest["peerDependencies"]).toEqual(
      Object.fromEntries(PI_HOST_PACKAGES.map((name) => [name, "*"])),
    )
    expect(manifest).not.toHaveProperty("dependencies")
    expect(HOST_MODULES.toSorted()).toEqual([...PI_HOST_PACKAGES].toSorted())
  })

  test("is what a git install of the repository root finds: the root pi key points at the build", () => {
    const rootPi = readJson("package.json")["pi"] as Record<string, ReadonlyArray<string>>
    const fromRoot = (entries: ReadonlyArray<string> = []) =>
      entries.map((entry) => resolve(REPOSITORY, entry))
    const fromPackage = (entries: ReadonlyArray<string>) =>
      entries.map((entry) => resolve(REPOSITORY, DIST_DIRECTORY, entry))
    const own = manifest["pi"] as Record<string, ReadonlyArray<string>>
    expect(Object.keys(rootPi).toSorted()).toEqual(Object.keys(own).toSorted())
    for (const [kind, entries] of Object.entries(own))
      expect({ kind, paths: fromRoot(rootPi[kind]) }).toEqual({
        kind,
        paths: fromPackage(entries),
      })
  })
})

describe("the runtime scripts", () => {
  const scriptsOf = (path: string) =>
    generated.find((file) => file.path === `${DIST_DIRECTORY}/${path}`)

  test("the package ships the wrapper, its empty Bun config and the runtime bundle", () => {
    for (const path of ["scripts/holyagent", "scripts/empty-bunfig.toml", "scripts/holyagent.js"])
      expect({ path, shipped: scriptsOf(path) !== undefined }).toEqual({ path, shipped: true })
    expect(scriptsOf("scripts/holyagent")?.executable).toBe(true)
    expect(statSync(join(REPOSITORY, DIST_DIRECTORY, "scripts/holyagent")).mode & 0o111).not.toBe(0)
  })

  test("the manifest lists the extension, script and skill folders as the package files, and they exist", () => {
    const manifest = JSON.parse(scriptsOf("package.json")?.content ?? "{}") as {
      files?: Array<string>
    }
    expect(manifest.files).toEqual([...PACKAGE_FILES])
    for (const entry of PACKAGE_FILES)
      expect(generated.some((file) => file.path.startsWith(`${DIST_DIRECTORY}/${entry}/`))).toBe(
        true,
      )
  })

  test("the wrapper is the Claude plugin's, with the Pi package's root in its one hint", () => {
    const claude = read("packages/integrations/claude/src/wrapper.sh").split("\n").slice(1)
    const pi = (scriptsOf("scripts/holyagent")?.content ?? "").split("\n").slice(2)
    expect(pi.join("\n")).toBe(
      claude.join("\n").replaceAll("${CLAUDE_PLUGIN_ROOT}", PI_ROOT_PLACEHOLDER),
    )
    expect(pi.join("\n")).not.toContain("CLAUDE")
  })

  test("the bundle answers config and otherwise is the CLI", async () => {
    const root = await mkdtemp(join(tmpdir(), "holyagent-pi-bundle-run-"))
    const script = join(REPOSITORY, DIST_DIRECTORY, "scripts/holyagent")
    const call = async (...args: Array<string>) => {
      const child = Bun.spawn(["sh", script, ...args], {
        cwd: root,
        env: { ...process.env, HOLYAGENT_HOME: join(root, "home") },
        stdout: "pipe",
        stderr: "pipe",
      })
      return {
        stdout: await new Response(child.stdout).text(),
        stderr: await new Response(child.stderr).text(),
        code: await child.exited,
      }
    }
    expect((await call("--version")).stdout.trim()).toBe(packageJson.version)
    const config = await call("config", join(root, ".holyagent"))
    expect(config.code).toBe(0)
    expect(JSON.parse(config.stdout)).toMatchObject({ pi: { enable: true } })
    expect((await call("status")).stdout).toBe("intents: []\n")
    await rm(root, { recursive: true, force: true })
  })
})

describe("the skills", () => {
  const skills = generated.filter((file) => file.path.startsWith(`${DIST_DIRECTORY}/skills/`))

  test("are the files of the family's skills, one for one", () => {
    expect(skills.map((file) => file.path.slice(`${DIST_DIRECTORY}/skills/`.length))).toEqual(
      sourceSkills,
    )
    expect(FAMILIES).toContain(PI_FAMILY)
  })

  test("each SKILL.md names its folder and has a description, as Pi's skill rules require", () => {
    for (const file of skills.filter((entry) => entry.path.endsWith("/SKILL.md"))) {
      const folder = file.path.split("/").at(-2)
      const frontmatter = file.content.split("\n---\n")[0] ?? ""
      expect({
        path: file.path,
        name: new RegExp(`^name: ${folder}$`, "m").test(frontmatter),
      }).toEqual({ path: file.path, name: true })
      expect(/^description: \S/m.test(frontmatter)).toBe(true)
    }
  })

  test("carry the design core and the materiality definition, never their markers", () => {
    for (const file of skills) {
      expect(file.content).not.toContain("<!-- design-core -->")
      expect(file.content).not.toContain("<!-- materiality -->")
    }
  })
})

describe("the extension", () => {
  const extension = generated.find((file) => file.path.endsWith(EXTENSION_OUTPUT))

  test("is a default-exported factory that registers the role flag and handlers and starts nothing", async () => {
    const root = await mkdtemp(join(tmpdir(), "holyagent-pi-extension-"))
    const path = join(root, "extension.mjs")
    await Bun.write(path, extension?.content ?? "")
    const loaded = (await import(path)) as { default: (pi: unknown) => unknown }
    const used: Array<string> = []
    const api = {
      registerFlag: (name: string) => void used.push(`registerFlag ${name}`),
      on: (event: string) => void used.push(`on ${event}`),
    }
    expect(typeof loaded.default).toBe("function")
    expect(loaded.default(api)).toBeUndefined()
    expect(used.toSorted()).toEqual([
      "on before_agent_start",
      "on session_compact",
      "on session_shutdown",
      "on session_start",
      "registerFlag holyagent-role",
    ])
    await rm(root, { recursive: true, force: true })
  })

  test("loads under Node, which has no Bun global", async () => {
    const node = Bun.which("node")
    if (node === null) return
    const run = Bun.spawn(
      [
        node,
        "--input-type=module",
        "-e",
        `const m = await import(${JSON.stringify(join(REPOSITORY, DIST_DIRECTORY, EXTENSION_OUTPUT))}); process.stdout.write(typeof m.default + " " + typeof globalThis.Bun)`,
      ],
      { stdout: "pipe", stderr: "pipe" },
    )
    expect(await new Response(run.stdout).text()).toBe("function undefined")
    expect(await run.exited).toBe(0)
  })

  test("leaves the host modules as imports, not bundled", async () => {
    const root = await mkdtemp(join(tmpdir(), "holyagent-pi-bundle-"))
    const entry = join(root, "extension.ts")
    await Bun.write(
      entry,
      [
        ...HOST_MODULES.map((name, at) => `import * as host${at} from "${name}"`),
        `import { Type } from "typebox/compile"`,
        `export default () => [${HOST_MODULES.map((_name, at) => `host${at}`).join(", ")}, Type]`,
      ].join("\n"),
    )
    const text = await bundleExtension(entry, "source.ts")
    for (const name of HOST_MODULES) expect(text).toContain(`from "${name}"`)
    expect(text).toContain(`from "typebox/compile"`)
    expect(text).toStartWith("// Generated by packages/integrations/pi/build.ts from source.ts;")
    await rm(root, { recursive: true, force: true })
  })

  test("drops Bun's module comments for a repository path that contains a space", async () => {
    const root = await mkdtemp(join(tmpdir(), "holyagent-pi-"))
    const folder = join(root, "my repo", "src")
    await Bun.write(join(folder, "dep.ts"), "export const dep = 1\n")
    await Bun.write(
      join(folder, "entry.ts"),
      'import { dep } from "./dep.ts"\nexport default () => dep\n',
    )
    const text = await bundleExtension(join(folder, "entry.ts"), "source.ts")
    expect(text.split("\n").filter((line) => /^\/\/ .*\.ts$/.test(line))).toEqual([])
    expect(text).toContain("dep = 1")
    await rm(root, { recursive: true, force: true })
  })
})
